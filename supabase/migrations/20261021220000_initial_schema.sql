create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.claim_initial_admin()
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := auth.uid();
  caller_email text;
  profile_row public.profiles;
  created_admin_id bigint;
begin
  if caller_id is null then
    raise exception 'Authentication required';
  end if;

  select lower(email) into caller_email
  from auth.users
  where id = caller_id
    and email_confirmed_at is not null;

  if caller_email is distinct from 'ramosjaredonarse07@gmail.com' then
    raise exception 'A verified configured administrator account is required to claim the first admin account';
  end if;

  perform pg_advisory_xact_lock(hashtext('caprafitness-initial-admin'));

  if exists (select 1 from public.profiles where role in ('admin', 'staff')) then
    select * into profile_row from public.profiles where id = caller_id;
    if profile_row.role in ('admin', 'staff') then
      return profile_row;
    end if;
    raise exception 'The initial administrator has already been claimed';
  end if;

  insert into public.admin_staff (full_name, email, role, status)
  values (
    coalesce(nullif((select full_name from public.profiles where id = caller_id), ''), 'Capra Fitness Administrator'),
    caller_email,
    'admin',
    'active'
  )
  returning admin_id into created_admin_id;

  update public.profiles
  set role = 'admin',
      admin_id = created_admin_id,
      updated_at = now()
  where id = caller_id
  returning * into profile_row;

  return profile_row;
end;
$$;

revoke all on function public.claim_initial_admin() from public, anon;
grant execute on function public.claim_initial_admin() to authenticated;

